"""Tables and figures of the out-of-sample test, for the report.

Reads the three results of a finished test (alphas_<v>.csv, summary_<v>.csv,
backtest_<v>_test.parquet) and the factor table; computes nothing new on the
strategy except cumulative values and rolling means for the figures. It changes
no result and reads no forecast. Every input is checked against the SHA-256
recorded at the end of the step that produced it (resources/test_steps/).

Run from Project/:  python scripts/reports/1_results_tables.py --version A
Outputs: reports/tables_<v>.md, reports/figures/<v>_*.png
"""
import argparse
import hashlib
import io
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
PROCESSED = ROOT / "data" / "processed"
STEPS = ROOT / "resources" / "test_steps"
OUT = ROOT / "reports"

CONFIGS = [
    ("gbrt_all_d1", "Trees, all sizes, first day (MAIN)"),
    ("gbrt_large_d1", "Trees, large universe, first day"),
    ("ridge_all_d1", "Ridge, all sizes, first day"),
    ("ridge_large_d1", "Ridge, large universe, first day"),
    ("gbrt_all_close", "Trees, all sizes, close to close"),
    ("gbrt_large_close", "Trees, large universe, close to close"),
    ("ridge_all_close", "Ridge, all sizes, close to close"),
    ("ridge_large_close", "Ridge, large universe, close to close"),
    ("gbrt_all_d1_cap01", "Trees, all sizes, first day, cap 1 %"),
    ("gbrt_large_d1_cap01", "Trees, large universe, first day, cap 1 %"),
]
PERIODS = ["1993-2025", "1993-2008", "2009-2025"]
MODELS = ["CAPM", "FF3", "FF5", "FF5_MOM"]
RETURNS = [("gross", "Gross"), ("net", "Net"),
           ("net_with_commission_stress", "Net + commission stress")]


def read_checked(version: str, step: str, name: str) -> bytes:
    """Bytes of a result, refused unless they match the hash of the one completed attempt."""
    done = []
    for path in sorted(STEPS.glob(f"*_{version}_{step}.attempt*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        if record.get("status") == "done":
            done.append(record)
    if len(done) != 1:
        raise SystemExit(f"{step} of version {version}: {len(done)} completed attempts, expected 1")
    expected = done[0]["outputs_sha256"][name]
    data = (PROCESSED / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise SystemExit(f"{name}: SHA-256 differs from the one recorded by the test step")
    return data


def pct(x: float, digits: int = 2) -> str:
    text = f"{100 * x:.{digits}f}"
    return text[1:] if text.startswith("-") and float(text) == 0 else text


def alpha_cell(alphas: pd.DataFrame, config: str, period: str, returns: str, model: str) -> str:
    row = alphas[(alphas.config == config) & (alphas.period == period)
                 & (alphas.returns == returns) & (alphas.factor_model == model)]
    if len(row) != 1:
        raise SystemExit(f"alpha row not unique: {config} {period} {returns} {model}")
    r = row.iloc[0]
    return f"{pct(r.alpha_annual)} ({r.t_alpha:.2f})"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", required=True, choices=["A", "B"])
    v = parser.parse_args().version

    alphas = pd.read_csv(io.BytesIO(read_checked(v, "alphas", f"alphas_{v}.csv")))
    summary = pd.read_csv(io.BytesIO(read_checked(v, "alphas", f"summary_{v}.csv")))
    bt = pd.read_parquet(io.BytesIO(read_checked(v, "backtest", f"backtest_{v}_test.parquet")))
    factors = pd.read_parquet(PROCESSED / "ff_factors_monthly.parquet")

    expected = {c for c, _ in CONFIGS}
    if set(summary.config) != expected or set(bt.config) != expected:
        raise SystemExit("unexpected set of configurations")

    lines = [f"# Version {v}: tables of the out-of-sample test (1993-2025)", "",
             "Generated by `scripts/reports/1_results_tables.py` from `alphas_" + v
             + ".csv`, `summary_" + v + ".csv` and `backtest_" + v + "_test.parquet`.",
             "Returns and alphas in % a year; t-statistics (Newey-West, 6 lags) in parentheses;",
             "costs in basis points of the fund a month; turnover = sum of |trades| a month, % of the fund.", ""]

    # Table 1: performance and mechanics, by configuration and period
    for period in PERIODS:
        lines += [f"## Performance and mechanics, {period}", "",
                  "| Configuration | Gross exc. ret. | Net exc. ret. (t) | Vol. | Sharpe | Net minus market (t) "
                  "| Spread bp | Impact bp | Comm. stress bp | Turnover filled | Cash | Stocks held "
                  "| Effective stocks | Largest weight (max) |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for config, label in CONFIGS:
            s = summary[(summary.config == config) & (summary.period == period)]
            if len(s) != 1:
                raise SystemExit(f"summary row not unique: {config} {period}")
            s = s.iloc[0]
            lines.append(
                f"| {label} | {pct(s.excess_return_gross_annual)} | {pct(s.excess_return_net_annual)} "
                f"({s.t_excess_return_net:.2f}) | {pct(s.volatility_net_annual, 1)} | {s.sharpe_net_annual:.2f} "
                f"| {pct(s.net_minus_market_annual)} ({s.t_net_minus_market:.2f}) "
                f"| {s.cost_spread_bp_month:.1f} | {s.cost_impact_bp_month:.1f} "
                f"| {s.commission_stress_bp_month:.1f} | {pct(s.turnover_filled_month, 0)} "
                f"| {pct(s.cash_after_trades_mean, 1)} | {s.stocks_held_median:.0f} "
                f"| {s.effective_stocks_median:.0f} | {pct(s.largest_weight_max, 1)} |")
        m = summary[summary.period == period].iloc[0]
        lines += ["", f"Market (Ken French, excess return): {pct(m.market_excess_return_annual)} % a year, "
                  f"Sharpe {m.market_sharpe_annual:.2f}.", ""]

    # Table 2: alphas
    for period in PERIODS:
        for returns, rlabel in RETURNS:
            lines += [f"## Alphas, {rlabel.lower()}, {period}", "",
                      "| Configuration | CAPM | FF3 | FF5 | FF5 + momentum |", "|---|---|---|---|---|"]
            for config, label in CONFIGS:
                cells = [alpha_cell(alphas, config, period, returns, mo) for mo in MODELS]
                lines.append(f"| {label} | " + " | ".join(cells) + " |")
            lines.append("")

    # Table 3: loadings of the main configuration and the conditional diagnostic
    main_rows = alphas[(alphas.config == "gbrt_all_d1") & (alphas.period == "1993-2025")
                       & (alphas.returns == "net")
                       & alphas.factor_model.isin(["FF5_MOM", "FF5_MOM_conditional"])]
    lines += ["## Main configuration, net, 1993-2025: loadings", "",
              "| Model | Alpha % a year (t) | Mkt | SMB | HML | RMW | CMA | MOM | R2 |",
              "|---|---|---|---|---|---|---|---|---|"]
    for _, r in main_rows.iterrows():
        lines.append(f"| {r.factor_model} | {pct(r.alpha_annual)} ({r.t_alpha:.2f}) | "
                     + " | ".join(f"{r[f'beta_{i}']:.2f}" for i in range(1, 7)) + f" | {r.r2:.3f} |")
    lines += ["", "The conditional model adds the products of the six factors with the share of the fund",
              "invested at the previous month end (centred); the loadings shown are those at the mean share.", ""]

    # Table 4: costs and mechanics of the main configuration by calendar block
    d = bt[bt.config == "gbrt_all_d1"].sort_values("yyyymm").copy()
    d["year"] = d.yyyymm // 100
    blocks = [(1993, 1996), (1997, 2000), (2001, 2004), (2005, 2008), (2009, 2012),
              (2013, 2016), (2017, 2020), (2021, 2025)]
    lines += ["## Main configuration: mechanics by block of years", "",
              "| Years | Spread bp | Impact bp | Turnover filled | Cash | Stocks held | Effective stocks "
              "| Largest weight (mean) |", "|---|---|---|---|---|---|---|---|"]
    for a, b in blocks:
        x = d[(d.year >= a) & (d.year <= b)]
        lines.append(f"| {a}-{b} | {1e4 * x.cost_spread.mean():.1f} | {1e4 * x.cost_impact.mean():.1f} "
                     f"| {pct(x.turnover_filled.mean(), 0)} | {pct(x.cash_after_trades.mean(), 1)} "
                     f"| {x.stocks_held_after_trades.median():.0f} | {x.effective_stocks.median():.0f} "
                     f"| {pct(x.largest_weight_after_trades.mean(), 1)} |")
    lines.append("")

    OUT.mkdir(exist_ok=True)
    (OUT / "figures").mkdir(exist_ok=True)
    (OUT / f"tables_{v}.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    # Figures
    f = factors[(factors.yyyymm >= 199301) & (factors.yyyymm <= 202512)].sort_values("yyyymm")
    dates = pd.to_datetime(f.yyyymm.astype(str), format="%Y%m") + pd.offsets.MonthEnd(0)
    if len(f) != 396:
        raise SystemExit("factor table: 396 months expected")
    market = (1 + f.mkt_excess.to_numpy() + f.risk_free.to_numpy()).cumprod()

    def series(config: str, column: str):
        x = bt[bt.config == config].sort_values("yyyymm")
        if list(x.yyyymm) != list(f.yyyymm):
            raise SystemExit(f"{config}: calendar differs from the factor table")
        return x[column].to_numpy()

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(dates, market, color="black", lw=1.6, label="Market (Ken French, value-weighted)")
    for config, column, label, style in [
        ("gbrt_all_d1", "ret_gross", "Trees, all sizes: gross", dict(color="tab:blue", ls="--")),
        ("gbrt_all_d1", "ret_net", "Trees, all sizes: net (MAIN)", dict(color="tab:blue")),
        ("gbrt_large_d1", "ret_net", "Trees, large universe: net", dict(color="tab:cyan")),
        ("ridge_all_d1", "ret_net", "Ridge, all sizes: net", dict(color="tab:red")),
        ("ridge_large_d1", "ret_net", "Ridge, large universe: net", dict(color="tab:orange")),
    ]:
        ax.plot(dates, (1 + series(config, column)).cumprod(), lw=1.2, label=label, **style)
    ax.set_yscale("log")
    ax.set_ylabel("Value of 1 invested at the end of 1992 (log scale)")
    ax.set_title(f"Version {v}: cumulative value, fund against the market, 1993-2025")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT / "figures" / f"{v}_cumulative_value.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4))
    for config, label, color in [("gbrt_all_d1", "Trees, all sizes, cap 10 % (MAIN)", "tab:blue"),
                                 ("gbrt_large_d1", "Trees, large universe, cap 10 %", "tab:cyan"),
                                 ("gbrt_all_d1_cap01", "Trees, all sizes, cap 1 %", "tab:gray"),
                                 ("ridge_all_d1", "Ridge, all sizes, cap 10 %", "tab:red")]:
        ax.plot(dates, 100 * series(config, "cash_after_trades"), lw=1.0, label=label, color=color)
    ax.set_ylabel("Cash after the trades, % of the fund")
    ax.set_title(f"Version {v}: share of the fund in cash")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT / "figures" / f"{v}_cash_share.png", dpi=150)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    for ax, config, title in [(axes[0], "gbrt_all_d1", "Trees, all sizes (MAIN)"),
                              (axes[1], "ridge_all_d1", "Ridge, all sizes")]:
        spread = pd.Series(1e4 * series(config, "cost_spread")).rolling(12).mean()
        impact = pd.Series(1e4 * series(config, "cost_impact")).rolling(12).mean()
        stress = pd.Series(1e4 * series(config, "cost_commission_stress")).rolling(12).mean()
        ax.stackplot(dates, spread, impact, labels=["Half spread", "Price impact"],
                     colors=["tab:blue", "tab:orange"], alpha=0.8)
        ax.plot(dates, spread + impact + stress, color="black", lw=1.0, ls="--",
                label="With commission stress")
        ax.set_title(title, fontsize=10)
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("Basis points of the fund a month (12-month mean)")
    axes[0].legend(fontsize=8)
    fig.suptitle(f"Version {v}: trading costs through time")
    fig.tight_layout()
    fig.savefig(OUT / "figures" / f"{v}_costs.png", dpi=150)
    plt.close(fig)

    main = summary[(summary.config == "gbrt_all_d1") & (summary.period == "1993-2025")].iloc[0]
    print(f"tables_{v}.md and 3 figures written to {OUT}.")
    print(f"Main configuration, net, FF5 + momentum, 1993-2025: "
          f"{alpha_cell(alphas, 'gbrt_all_d1', '1993-2025', 'net', 'FF5_MOM')} % a year (t); "
          f"net excess return {pct(main.excess_return_net_annual)} %, market "
          f"{pct(main.market_excess_return_annual)} %.")
    print(f"Value of 1 at the end of 2025: market {market[-1]:.2f}; "
          f"main net {(1 + series('gbrt_all_d1', 'ret_net')).prod():.2f}; "
          f"main gross {(1 + series('gbrt_all_d1', 'ret_gross')).prod():.2f}.")


if __name__ == "__main__":
    main()
